def export_document(
    title: str,
    md_text: str,
    fmt: str = "docx",
    sources: list[dict] | None = None,
    created_at: str | None = None,
) -> tuple[io.BytesIO, str, str]:
    """Export an AI response as a downloadable document.

    Args:
        title: Document title
        md_text: Markdown-formatted AI response text
        fmt: "docx" or "pdf"
        sources: Optional list of source metadata dicts
        created_at: Optional timestamp string

    Returns:
        Tuple of (BytesIO buffer, filename, media_type)
    """
    # Sanitize LLM output before any rendering
    md_text = sanitize_output(md_text)

    # Sanitize title for filename
    safe_title = re.sub(r"[^\w\s-]", "", title[:50]).strip().replace(" ", "_")
    if not safe_title:
        safe_title = "lawttorney_export"
    timestamp = datetime.now().strftime("%Y%m%d_%H%M")

    if fmt == "pdf":
        buf = generate_pdf(title, md_text, sources, created_at)
        filename = f"{safe_title}_{timestamp}.pdf"
        media_type = "application/pdf"
    else:
        buf = generate_docx(title, md_text, sources, created_at)
        filename = f"{safe_title}_{timestamp}.docx"
        media_type = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"

    log.info("Export complete", format=fmt, filename=filename)
    return buf, filename, media_type