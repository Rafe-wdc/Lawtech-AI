"""Unit tests for core.url_filter.

Covers the three surfaces the module scrubs:
  1. `is_whitelisted_url` — host whitelist decisions
  2. `sanitize_source_records` — API `source_metadata` payload sanitiser
  3. `sanitize_prose` — final_response prose stripper
  4. `StreamingUrlFilter` — rolling-buffer SSE token scrubber

Whitelist policy: URLs on `lawttorney.s3.*.amazonaws.com` (HC judgment PDFs)
and `api.sci.gov.in` (SCI PDFs) are kept. Every other URL is stripped
(Google Search grounding citations, tier-3 web_search_fallback URLs,
authoritative-domain URLs like indiankanoon.org, government portals, etc.).
"""
from __future__ import annotations

import pytest

from core.url_filter import (
    StreamingUrlFilter,
    is_whitelisted_url,
    sanitize_prose,
    sanitize_source_records,
)


# ---------------------------------------------------------------------------
# is_whitelisted_url
# ---------------------------------------------------------------------------

class TestIsWhitelistedUrl:
    def test_none_and_empty(self):
        assert is_whitelisted_url(None) is False
        assert is_whitelisted_url("") is False
        assert is_whitelisted_url("   ") is False

    def test_lawttorney_s3_ap_south_1(self):
        assert is_whitelisted_url(
            "https://lawttorney.s3.ap-south-1.amazonaws.com/bombay high court/xyz.pdf"
        ) is True

    def test_lawttorney_s3_other_region(self):
        assert is_whitelisted_url(
            "https://lawttorney.s3.us-east-1.amazonaws.com/supreme/case.pdf"
        ) is True

    def test_sci_api(self):
        assert is_whitelisted_url(
            "https://api.sci.gov.in/supremecourt/2017/39058/xyz.pdf"
        ) is True

    def test_case_insensitive(self):
        assert is_whitelisted_url(
            "HTTPS://LAWTTORNEY.S3.AP-SOUTH-1.AMAZONAWS.COM/xyz.pdf"
        ) is True

    def test_external_hosts_rejected(self):
        assert is_whitelisted_url("https://indiankanoon.org/doc/12345/") is False
        assert is_whitelisted_url("https://barandbench.com/news/xyz") is False
        assert is_whitelisted_url("https://vakilsearch.com/blog") is False
        assert is_whitelisted_url("https://google.com") is False
        assert is_whitelisted_url("https://legislative.gov.in") is False

    def test_lookalike_hosts_rejected(self):
        # Prefix-match must be strict — a subdomain that only *contains*
        # "lawttorney" but doesn't start with it should be rejected.
        assert is_whitelisted_url("https://evil.com/lawttorney.s3.amazonaws.com/x") is False
        assert is_whitelisted_url("https://api.sci.gov.in.evil.com/xyz") is False
        assert is_whitelisted_url("https://not-api.sci.gov.in/xyz") is False

    def test_http_vs_https(self):
        # Both schemes on whitelisted hosts should be accepted (defensive —
        # nothing in our pipeline emits plain http today, but be safe).
        assert is_whitelisted_url("http://api.sci.gov.in/x") is True
        assert is_whitelisted_url("http://lawttorney.s3.ap-south-1.amazonaws.com/x") is True


