class TestStreamingUrlFilter:
    def test_no_urls_passes_through(self):
        f = StreamingUrlFilter()
        assert f.push("hello ") == "hello "
        assert f.push("world") == "world"
        assert f.flush() == ""

    def test_url_split_across_two_tokens(self):
        # URL "https://evil.com/foo" arrives as "https://ev" + "il.com/foo "
        f = StreamingUrlFilter()
        # First chunk contains scheme + partial host — should HOLD from `https://`.
        out1 = f.push("prefix https://ev")
        assert out1 == "prefix "
        # Second chunk completes the URL with a trailing space terminator.
        out2 = f.push("il.com/foo suffix")
        assert "evil.com" not in out2
        assert "suffix" in out2

    def test_whitelisted_url_split_across_tokens_kept(self):
        f = StreamingUrlFilter()
        out1 = f.push("PDF: https://api.sci.gov.in/x")
        # Buffer holds from `https://` since no terminator arrived yet.
        assert "https://api.sci.gov.in" not in out1
        out2 = f.push("yz.pdf here")
        combined = out1 + out2
        assert "https://api.sci.gov.in/xyz.pdf" in combined
        assert "here" in combined

    def test_scheme_partial_at_end_of_chunk(self):
        # "htt" at end of a chunk — must be held, not emitted, in case the
        # next chunk completes it into a URL.
        f = StreamingUrlFilter()
        out1 = f.push("visit htt")
        assert out1 == "visit "
        out2 = f.push("ps://evil.com/x done")
        assert "evil.com" not in out2
        assert "done" in out2

    def test_flush_drains_held_partial(self):
        # If the stream closes with an unfinished URL in the buffer, flush()
        # must drain the tail through sanitize_prose.
        f = StreamingUrlFilter()
        f.push("check https://evil.com/foo")  # no terminator
        tail = f.flush()
        assert "evil.com" not in tail

    def test_url_immediately_at_chunk_start(self):
        f = StreamingUrlFilter()
        out = f.push("https://api.sci.gov.in/x.pdf yes")
        assert "https://api.sci.gov.in/x.pdf" in out
        assert "yes" in out

    def test_many_small_chunks(self):
        f = StreamingUrlFilter()
        assembled = ""
        for ch in "prefix https://evil.com/foo suffix":
            assembled += f.push(ch)
        assembled += f.flush()
        assert "evil.com" not in assembled
        assert "prefix" in assembled
        assert "suffix" in assembled

    def test_multiple_urls_in_single_chunk(self):
        f = StreamingUrlFilter()
        out = f.push("a https://evil.com/x b https://api.sci.gov.in/y.pdf c")
        assert "evil.com" not in out
        assert "https://api.sci.gov.in/y.pdf" in out
        assert "a " in out
        assert " b " in out
        assert " c" in out

    def test_empty_push_returns_empty(self):
        f = StreamingUrlFilter()
        assert f.push("") == ""
        assert f.flush() == ""
