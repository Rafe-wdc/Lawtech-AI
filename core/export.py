def generate_pdf(
    title: str,
    md_text: str,
    sources: list[dict] | None = None,
    created_at: str | None = None,
) -> io.BytesIO:
    """Generate a professionally formatted PDF from markdown text.

    Uses PyMuPDF's Story API for HTML/CSS rendering with full Unicode support.

    Args:
        title: Document title
        md_text: Markdown-formatted AI response
        sources: Optional list of source metadata dicts
        created_at: Optional timestamp string

    Returns:
        BytesIO buffer containing the PDF file
    """
    import fitz

    date_str = created_at or datetime.now().strftime("%d %B %Y")

    # Convert markdown to HTML
    body_html = _md_to_html(md_text)

    # Build citations HTML
    citations_html = ""
    if sources:
        citations_html = "<h2>Sources & Citations</h2>"
        for idx, src in enumerate(sources, 1):
            src_title = src.get("title", "Unknown Source")
            src_type = src.get("source_type", "")
            agent = src.get("agent_name", "")
            web_url = src.get("web_url", "")
            line = f"{idx}. {src_title}"
            if src_type:
                line += f" [{src_type}]"
            if agent:
                line += f" (via {agent})"
            if web_url:
                line += f" - {web_url}"
            citations_html += f'<p class="citation">{line}</p>'

    # Assemble full HTML document
    html = f"""<!DOCTYPE html>
<html>
<head><meta charset="utf-8"></head>
<body>
    <h1>{_escape_html(title)}</h1>
    <p class="meta">Date: {date_str}</p>
    {body_html}
    {citations_html}
    <p class="footer">Generated by Lawttorney - Indian Legal AI Assistant</p>
</body>
</html>"""

    buf = io.BytesIO()

    try:
        # Use Story API: Story + DocumentWriter for multi-page PDF
        story = fitz.Story(html=html, user_css=_PDF_CSS)
        page_rect = fitz.Rect(0, 0, 595.28, 841.89)
        content_rect = fitz.Rect(72, 72, 595.28 - 72, 841.89 - 72)

        writer = fitz.DocumentWriter(buf)

        def rectfn(rect_num, filled):
            """Called by Story.write() to get the rectangle for each content area."""
            return content_rect, page_rect, None  # content_rect, mediabox, None

        story.write(writer, rectfn)
        writer.close()
        buf.seek(0)
    except Exception as story_err:
        log.warning("PDF Story rendering failed, using text-based fallback",
                    error=str(story_err))
        buf = io.BytesIO()
        pdf_doc = fitz.open()
        _generate_pdf_simple(pdf_doc, title, md_text, date_str, sources)
        pdf_doc.save(buf)
        pdf_doc.close()

    buf.seek(0)
    log.info("PDF generated", title=title[:60], size_kb=buf.getbuffer().nbytes // 1024)
    return buf


def _generate_pdf_simple(
    doc,
    title: str,
    md_text: str,
    date_str: str,
    sources: list[dict] | None = None,
):
    """Simple text-based PDF fallback when Story API is unavailable."""
    import fitz

    # Strip markdown formatting for plain text
    text = md_text
    text = re.sub(r"#{1,3}\s+", "", text)  # Remove heading markers
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)  # Remove bold
    text = re.sub(r"\*(.+?)\*", r"\1", text)  # Remove italic
    text = re.sub(r"`(.+?)`", r"\1", text)  # Remove code
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)  # Remove links

    full_text = f"{title}\n\nDate: {date_str}\n\n{'='*60}\n\n{text}"

    if sources:
        full_text += "\n\nSources & Citations\n" + "-" * 40 + "\n"
        for idx, src in enumerate(sources, 1):
            full_text += f"{idx}. {src.get('title', 'Unknown')}\n"

    full_text += f"\n\n{'='*60}\nGenerated by Lawttorney - Indian Legal AI Assistant"

    # Insert text page by page
    fontsize = 11
    margin = 72
    page_rect = fitz.Rect(0, 0, 595.28, 841.89)
    text_rect = fitz.Rect(margin, margin, 595.28 - margin, 841.89 - margin)

    remaining = full_text
    while remaining:
        page = doc.new_page(width=page_rect.width, height=page_rect.height)
        # insert_textbox returns remaining text that didn't fit
        rc = page.insert_textbox(
            text_rect,
            remaining,
            fontsize=fontsize,
            fontname="helv",
            align=fitz.TEXT_ALIGN_JUSTIFY,
        )
        if rc < 0:
            # Text overflowed — estimate how much fit and continue
            # Approximate chars per page
            chars_per_page = int(text_rect.width / (fontsize * 0.5) * text_rect.height / (fontsize * 1.3))
            remaining = remaining[chars_per_page:]
        else:
            remaining = ""


def _escape_html(text: str) -> str:
    """Escape HTML special characters."""
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


