class TestSanitizeSourceRecords:
    """Post-2026-08-22 policy: keep ONLY records with a whitelisted PDF URL."""

    def test_none_and_empty(self):
        assert sanitize_source_records(None) == []
        assert sanitize_source_records([]) == []

    def test_scenario_web_record_dropped(self):
        records = [{
            "source_type": "scenario",
            "title": "Some blog post",
            "web_url": "https://indiankanoon.org/doc/12345/",
            "web_title": "Some blog post",
            "agent_name": "Scenario",
        }]
        assert sanitize_source_records(records) == []

    def test_tier3_web_fallback_record_dropped(self):
        records = [{
            "source_type": "newacts",
            "title": "External blog on BNS §115",
            "web_url": "https://vakilsearch.com/blog/bns-115",
            "agent_name": "Newacts",
        }]
        assert sanitize_source_records(records) == []

    def test_ungrounded_ai_marker_dropped(self):
        # web_search_fallback's "no grounding" marker record — no URL, no PDF.
        # Under the new policy, no whitelisted URL means dropped.
        records = [{
            "source_type": "legal_concepts",
            "title": "AI-Generated Legal_Concepts Analysis",
            "content": ["Response generated by AI with web search grounding"],
            "agent_name": "Legal_Concepts",
        }]
        assert sanitize_source_records(records) == []

    def test_legislation_record_no_url_dropped(self):
        # Legislation records carry no URL field — dropped under new policy.
        records = [{
            "source_type": "legislation",
            "title": "Section 302 IPC",
            "content": ["Whoever commits murder..."],
            "section_number": "302",
            "act_name": "Indian Penal Code",
        }]
        assert sanitize_source_records(records) == []

    def test_document_agent_record_dropped(self):
        # PDF-chat agent records carry file_name, no URL — dropped.
        records = [{
            "source_type": "document",
            "title": "uploaded_contract.pdf",
            "file_name": "uploaded_contract.pdf",
            "content": ["Some extracted text..."],
        }]
        assert sanitize_source_records(records) == []

    def test_hc_judgment_record_kept(self):
        s3_url = "https://lawttorney.s3.ap-south-1.amazonaws.com/bombay high court/xyz.pdf"
        records = [{
            "source_type": "judgment",
            "title": "Some HC case",
            "doc_link": s3_url,
            "web_url": s3_url,
            "agent_name": "Judgment",
        }]
        cleaned = sanitize_source_records(records)
        assert len(cleaned) == 1
        assert cleaned[0]["doc_link"] == s3_url
        assert cleaned[0]["web_url"] == s3_url

    def test_sci_pdf_links_filtered(self):
        # Mixed pdf_links list: whitelisted entry survives, blog entry drops,
        # record kept because a whitelisted PDF remains.
        records = [{
            "source_type": "sci_judgment",
            "title": "Some SCI case",
            "pdf_links": [
                {"label": "SCI Judgment", "url": "https://api.sci.gov.in/supremecourt/x.pdf"},
                {"label": "Blog", "url": "https://barandbench.com/xyz"},
            ],
            "agent_name": "SCI_Judgment",
        }]
        cleaned = sanitize_source_records(records)
        assert len(cleaned) == 1
        assert len(cleaned[0]["pdf_links"]) == 1
        assert cleaned[0]["pdf_links"][0]["url"].startswith("https://api.sci.gov.in/")

    def test_record_with_external_web_url_but_valid_pdf_links_kept(self):
        # Kept because of whitelisted pdf_links entry; external web_url nulled.
        records = [{
            "source_type": "sci_judgment",
            "title": "Some case",
            "web_url": "https://external.com/x",
            "web_title": "External source",
            "pdf_links": [
                {"label": "SCI PDF", "url": "https://api.sci.gov.in/x.pdf"},
            ],
        }]
        cleaned = sanitize_source_records(records)
        assert len(cleaned) == 1
        assert cleaned[0]["web_url"] is None
        assert cleaned[0]["web_title"] is None
        assert cleaned[0]["pdf_links"][0]["url"].startswith("https://api.sci.gov.in/")

    def test_mixed_batch(self):
        s3_url = "https://lawttorney.s3.ap-south-1.amazonaws.com/hc/x.pdf"
        sci_url = "https://api.sci.gov.in/y.pdf"
        records = [
            {"source_type": "legislation", "title": "Section 302 IPC"},          # drop (no URL)
            {"source_type": "scenario", "web_url": "https://external.com/x"},    # drop
            {"source_type": "judgment", "doc_link": s3_url},                     # keep
            {"source_type": "newacts", "web_url": "https://vakilsearch.com/x"},  # drop
            {"source_type": "sci_judgment", "pdf_links": [{"url": sci_url}]},    # keep
            {"source_type": "document", "title": "upload.pdf"},                  # drop
        ]
        cleaned = sanitize_source_records(records)
        assert len(cleaned) == 2
        assert cleaned[0]["doc_link"] == s3_url
        assert cleaned[1]["pdf_links"][0]["url"] == sci_url

    def test_non_dict_entries_dropped(self):
        records = ["not a dict", {"source_type": "judgment",
                                  "doc_link": "https://lawttorney.s3.ap-south-1.amazonaws.com/x.pdf"}]
        cleaned = sanitize_source_records(records)
        assert len(cleaned) == 1
        assert cleaned[0]["source_type"] == "judgment"


