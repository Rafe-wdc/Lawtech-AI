def _create_docx_styles(doc):
    """Configure professional legal document styles on a python-docx Document."""
    from docx.shared import Pt, Inches, Cm, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.enum.style import WD_STYLE_TYPE

    # Page setup: A4, 1-inch margins
    for section in doc.sections:
        section.page_width = Cm(21.0)
        section.page_height = Cm(29.7)
        section.top_margin = Cm(2.54)
        section.bottom_margin = Cm(2.54)
        section.left_margin = Cm(2.54)
        section.right_margin = Cm(2.54)

    styles = doc.styles

    # Normal/body style
    normal = styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(11)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15

    # Heading styles
    for level, size, bold in [(1, 16, True), (2, 13, True), (3, 11, True)]:
        style = styles[f"Heading {level}"]
        style.font.name = "Times New Roman"
        style.font.size = Pt(size)
        style.font.bold = bold
        style.font.color.rgb = RGBColor(0x1A, 0x1A, 0x1A)
        style.paragraph_format.space_before = Pt(12)
        style.paragraph_format.space_after = Pt(6)

    # Citation style (custom)
    if "LT Citation" not in [s.name for s in styles]:
        citation_style = styles.add_style("LT Citation", WD_STYLE_TYPE.PARAGRAPH)
        citation_style.font.name = "Times New Roman"
        citation_style.font.size = Pt(9)
        citation_style.font.italic = True
        citation_style.font.color.rgb = RGBColor(0x55, 0x55, 0x55)
        citation_style.paragraph_format.left_indent = Cm(1.0)
        citation_style.paragraph_format.space_after = Pt(3)

    return doc


def _add_footer(doc, text: str = "Generated by Lawttorney - Indian Legal AI Assistant"):
    """Add footer text to all sections of the document."""
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    for section in doc.sections:
        footer = section.footer
        footer.is_linked_to_previous = False
        p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run.font.size = Pt(8)
        run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)
        run.font.italic = True


def _md_to_docx(doc, md_text: str):
    """Convert markdown text to python-docx document elements.

    Handles: headings, bold, italic, bullet lists, ordered lists, tables,
    code blocks, horizontal rules, and inline formatting.

    Sanitizes malformed tables before processing.
    """
    from docx.shared import Pt, RGBColor, Cm
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn

    md_text = _sanitize_md_tables(md_text)
    lines = md_text.split("\n")
    i = 0
    in_table = False
    table_rows = []

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # Skip empty lines
        if not stripped:
            i += 1
            continue

        # Code block (```)
        if stripped.startswith("```"):
            i += 1
            code_lines = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code_lines.append(lines[i])
                i += 1
            i += 1  # skip closing ```
            p = doc.add_paragraph()
            p.style = doc.styles["Normal"]
            run = p.add_run("\n".join(code_lines))
            run.font.name = "Courier New"
            run.font.size = Pt(9)
            run.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
            continue

        # Table row (|...|)
        if stripped.startswith("|") and stripped.endswith("|"):
            # Collect all table rows
            if not in_table:
                in_table = True
                table_rows = []
            # Skip separator rows (|---|---|)
            if re.match(r"^\|[\s\-:|]+\|$", stripped):
                i += 1
                continue
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            table_rows.append(cells)
            i += 1
            # Check if next line is still table
            if i >= len(lines) or not lines[i].strip().startswith("|"):
                # Flush table
                in_table = False
                if table_rows:
                    _add_table(doc, table_rows)
                table_rows = []
            continue

        # Heading (# ## ###)
        heading_match = re.match(r"^(#{1,3})\s+(.+)$", stripped)
        if heading_match:
            level = len(heading_match.group(1))
            text = heading_match.group(2).strip()
            p = doc.add_heading(text, level=level)
            i += 1
            continue

        # Horizontal rule (--- or ***)
        if re.match(r"^[-*_]{3,}$", stripped):
            # Add a thin line via paragraph border
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(6)
            p.paragraph_format.space_after = Pt(6)
            i += 1
            continue

        # Bullet list (- or * or +)
        if re.match(r"^[\-*+]\s+", stripped):
            text = re.sub(r"^[\-*+]\s+", "", stripped)
            p = doc.add_paragraph(style="List Bullet")
            _add_formatted_text(p, text)
            i += 1
            continue

        # Ordered list (1. 2. etc.). Legal drafts number paragraphs LITERALLY —
        # the verification clause refers to them by number ("the contents of
        # paragraphs 1 to 22 are true"), so the count must be stable and
        # continuous. Word's "List Number" style STRIPS the literal number and
        # auto-renumbers, which RESTARTS at every heading/interruption (e.g.
        # after "## Grounds for Bail") — corrupting the exact numbering the
        # drafter computed. Keep the literal "1. " as text in a hanging-indent
        # paragraph so the filed document matches the source verbatim. (The
        # HTML console has the same defect in its own renderMarkdown; this fix
        # is the one that matters for the filed .docx.)
        if re.match(r"^\d+\.\s+", stripped):
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.8)
            p.paragraph_format.first_line_indent = Cm(-0.8)
            _add_formatted_text(p, stripped)   # keep the literal number
            i += 1
            continue

        # Regular paragraph
        p = doc.add_paragraph()
        _add_formatted_text(p, stripped)
        i += 1


def _add_formatted_text(paragraph, text: str):
    """Add text with inline markdown formatting (bold, italic, code, links)."""
    from docx.shared import Pt, RGBColor

    # Pattern to split by inline formatting
    # Matches: **bold**, *italic*, `code`, [text](url)
    pattern = r"(\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`|\[[^\]]+\]\([^)]+\))"
    parts = re.split(pattern, text)

    for part in parts:
        if not part:
            continue
        # Bold
        if part.startswith("**") and part.endswith("**"):
            run = paragraph.add_run(part[2:-2])
            run.bold = True
        # Italic
        elif part.startswith("*") and part.endswith("*"):
            run = paragraph.add_run(part[1:-1])
            run.italic = True
        # Inline code
        elif part.startswith("`") and part.endswith("`"):
            run = paragraph.add_run(part[1:-1])
            run.font.name = "Courier New"
            run.font.size = Pt(9)
            run.font.color.rgb = RGBColor(0x66, 0x33, 0x99)
        # Link [text](url)
        elif part.startswith("[") and "](" in part:
            match = re.match(r"\[([^\]]+)\]\(([^)]+)\)", part)
            if match:
                run = paragraph.add_run(match.group(1))
                run.font.color.rgb = RGBColor(0x14, 0x3C, 0x78)
                run.underline = True
            else:
                paragraph.add_run(part)
        else:
            paragraph.add_run(part)


def _add_table(doc, rows: list[list[str]]):
    """Add a formatted table to the document."""
    from docx.shared import Pt, RGBColor, Cm
    from docx.oxml.ns import qn

    if not rows:
        return

    n_cols = max(len(r) for r in rows)
    table = doc.add_table(rows=len(rows), cols=n_cols)
    table.style = "Table Grid"

    for r_idx, row_data in enumerate(rows):
        for c_idx, cell_text in enumerate(row_data):
            if c_idx < n_cols:
                cell = table.rows[r_idx].cells[c_idx]
                cell.text = cell_text
                # Bold header row
                if r_idx == 0:
                    for p in cell.paragraphs:
                        for run in p.runs:
                            run.bold = True
                            run.font.size = Pt(9)
                else:
                    for p in cell.paragraphs:
                        for run in p.runs:
                            run.font.size = Pt(9)


def generate_docx(
    title: str,
    md_text: str,
    sources: list[dict] | None = None,
    created_at: str | None = None,
) -> io.BytesIO:
    """Generate a professionally formatted DOCX from markdown text.

    Args:
        title: Document title (from user query or custom)
        md_text: Markdown-formatted AI response
        sources: Optional list of source metadata dicts
        created_at: Optional timestamp string

    Returns:
        BytesIO buffer containing the DOCX file
    """
    from docx import Document
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = Document()
    _create_docx_styles(doc)

    # Title
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Date line
    date_str = created_at or datetime.now().strftime("%d %B %Y")
    date_para = doc.add_paragraph()
    date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = date_para.add_run(f"Date: {date_str}")
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)
    run.italic = True

    # Separator
    doc.add_paragraph("_" * 60)

    # Main content
    _md_to_docx(doc, md_text)

    # Sources/Citations section
    if sources:
        doc.add_heading("Sources & Citations", level=2)
        for idx, src in enumerate(sources, 1):
            src_title = src.get("title", "Unknown Source")
            src_type = src.get("source_type", "")
            agent = src.get("agent_name", "")
            web_url = src.get("web_url", "")

            citation_text = f"{idx}. {src_title}"
            if src_type:
                citation_text += f" [{src_type}]"
            if agent:
                citation_text += f" (via {agent})"
            if web_url:
                citation_text += f" - {web_url}"

            p = doc.add_paragraph(style="LT Citation")
            p.add_run(citation_text)

    # Footer
    _add_footer(doc)

    # Write to buffer
    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)

    log.info("DOCX generated", title=title[:60], size_kb=buf.getbuffer().nbytes // 1024)
    return buf


