class TestSanitizeProse:
    def test_none_and_empty(self):
        assert sanitize_prose(None) == ""
        assert sanitize_prose("") == ""
        assert sanitize_prose("no urls here") == "no urls here"

    def test_bare_external_url_stripped(self):
        text = "See https://indiankanoon.org/doc/123 for details."
        out = sanitize_prose(text)
        assert "indiankanoon.org" not in out
        # "See :" wrapper should also go
        assert "See" not in out or "See" in out and "https" not in out

    def test_bare_sci_url_kept(self):
        text = "Refer to https://api.sci.gov.in/xyz.pdf for the judgment."
        out = sanitize_prose(text)
        assert "https://api.sci.gov.in/xyz.pdf" in out

    def test_bare_s3_url_kept(self):
        text = "PDF at https://lawttorney.s3.ap-south-1.amazonaws.com/x.pdf here."
        out = sanitize_prose(text)
        assert "lawttorney.s3.ap-south-1.amazonaws.com" in out

    def test_markdown_link_external_dropped_label_kept(self):
        text = "Read [my blog](https://ipleaders.in/xyz) for context."
        out = sanitize_prose(text)
        assert "ipleaders.in" not in out
        assert "my blog" in out  # label preserved

    def test_markdown_link_whitelisted_kept(self):
        text = "See [Judgment PDF](https://api.sci.gov.in/x.pdf)."
        out = sanitize_prose(text)
        assert "https://api.sci.gov.in/x.pdf" in out
        assert "[Judgment PDF]" in out

    def test_source_wrapper_stripped(self):
        text = "The court held X. Source: https://barandbench.com/news/xyz. Then Y."
        out = sanitize_prose(text)
        assert "barandbench.com" not in out
        assert "Source:" not in out
        assert "The court held X." in out
        assert "Then Y." in out

    def test_pdf_links_block_survives(self):
        text = (
            "**PDF Links:**\n"
            "- *Case A*: https://api.sci.gov.in/x.pdf\n"
            "- *Case B*: https://lawttorney.s3.ap-south-1.amazonaws.com/hc/y.pdf\n"
        )
        out = sanitize_prose(text)
        assert "**PDF Links:**" in out
        assert "https://api.sci.gov.in/x.pdf" in out
        assert "lawttorney.s3.ap-south-1.amazonaws.com" in out

    def test_mixed_pdf_links_external_dropped(self):
        text = (
            "**PDF Links:**\n"
            "- *SCI Case*: https://api.sci.gov.in/x.pdf\n"
            "- *Blog analysis*: https://livelaw.in/xyz\n"
        )
        out = sanitize_prose(text)
        assert "https://api.sci.gov.in/x.pdf" in out
        assert "livelaw.in" not in out

    def test_multiple_urls_mixed(self):
        text = (
            "Judgment: https://api.sci.gov.in/x.pdf and See https://google.com/y and "
            "[click](https://ipleaders.in/z) with bare https://vakilsearch.com/foo."
        )
        out = sanitize_prose(text)
        assert "https://api.sci.gov.in/x.pdf" in out
        assert "google.com" not in out
        assert "ipleaders.in" not in out
        assert "vakilsearch.com" not in out

    def test_retrieved_sources_footer_stripped(self):
        # LLM echoes the input `## Retrieved Sources` marker back into the
        # response as a trailing footer. Must be stripped.
        text = (
            "A Power of Attorney is a legal instrument...\n\n"
            "The Supreme Court held X in Suraj Lamp.\n\n"
            "## Retrieved Sources\n\n"
            "1. **sci-44015** Suraj Lamp and Industries Private Limited "
            "vs. State of Haryana, (2012) 1 SCC 656\n"
        )
        out = sanitize_prose(text)
        assert "## Retrieved Sources" not in out
        assert "sci-44015" not in out
        # Body content survives.
        assert "Power of Attorney" in out
        assert "Suraj Lamp" in out

    def test_sources_and_citations_footer_stripped(self):
        text = (
            "The main analysis is here.\n\n"
            "### Sources & Citations\n\n"
            "1. sci-44015 Some case\n"
            "2. leg-ipc-302 Section 302 IPC\n"
        )
        out = sanitize_prose(text)
        assert "Sources & Citations" not in out
        assert "sci-44015" not in out
        assert "leg-ipc-302" not in out
        assert "The main analysis" in out

    def test_bold_sources_footer_stripped(self):
        # Bold-wrapped variant: **Sources:** ...
        text = (
            "Body of the response.\n\n"
            "**Sources:**\n"
            "- hc-bombay-12345 Some HC case\n"
        )
        out = sanitize_prose(text)
        assert "Sources:" not in out
        assert "hc-bombay-12345" not in out
        assert "Body of the response." in out

    def test_inline_internal_id_stripped(self):
        # An internal id can leak on its own line mid-response too.
        text = (
            "The court held X. Y was the issue.\n"
            "1. **sci-44015** Suraj Lamp v. State of Haryana\n"
            "Then Z happened.\n"
        )
        out = sanitize_prose(text)
        assert "sci-44015" not in out
        assert "The court held X." in out
        assert "Then Z happened." in out

    def test_no_footer_no_change(self):
        # A response with no footer / no internal ids passes through untouched
        # (apart from URL scrubbing which does nothing here).
        text = (
            "The Powers-of-Attorney Act, 1882 governs POAs in India. "
            "See also Section 17(1) of the Registration Act, 1908."
        )
        out = sanitize_prose(text)
        # No URLs in the input — nothing to strip. Whitespace collapsing only.
        assert "Powers-of-Attorney Act, 1882" in out
        assert "Registration Act, 1908" in out


